from __future__ import annotations

import json

SYSTEM_PROMPT = """Ты — аналитик системы мониторинга социальных программ «СоцПульс AI».
Работай только с переданными данными. Не придумывай факты, цифры, причины и внешние сведения.
Если данных недостаточно для вывода — прямо укажи это.
Пиши кратко, управленческим языком на русском языке.
Главная задача: объяснить статус программы, выделить риски и предложить проверяемые действия.
Не называй правило риск-скоринга машинным обучением: в MVP это детерминированный риск-индикатор.
"""


def analysis_messages(context: dict[str, object]) -> list[dict[str, str]]:
    prompt = f"""Подготовь аналитическую записку по социальной программе.

Данные программы:
{json.dumps(context, ensure_ascii=False, indent=2)}

Структура ответа:
1. Краткий статус — 2-3 предложения.
2. Что идет хорошо — до 3 пунктов.
3. Риски и отклонения — до 3 пунктов, только на основе цифр.
4. Что проверить руководителю в первую очередь — до 3 конкретных действий.
5. Итог — одна фраза.
"""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": prompt},
    ]


def question_messages(context: dict[str, object], question: str) -> list[dict[str, str]]:
    prompt = f"""Данные программы:
{json.dumps(context, ensure_ascii=False, indent=2)}

Вопрос пользователя: {question}

Ответь только по этим данным. Если вопрос требует данных, которых здесь нет, скажи, каких именно данных не хватает.
"""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": prompt},
    ]
